df = pd.read_csv(io.StringIO(csv_data))

# Convert individual scores to percentages
df['FA_after_percent'] = df['FA_after'] * 100

# Calculate the cumulative (expanding) average
df['cumulative_mean'] = df['FA_after_percent'].expanding().mean()

# --- Plotting ---
plt.style.use('seaborn-v0_8-whitegrid')
plt.rcParams['font.family'] = 'serif'

# Create a compact figure
fig, ax = plt.subplots(figsize=(7, 4), dpi=150)

# Bar plot for cumulative average, without error bars
bars = ax.bar(
    df['step'],
    df['cumulative_mean'],
    color='#2E8B57',
    edgecolor='black',
    alpha=0.8,
    linewidth=0.8,
)

# --- Add text labels for the mean values ---
for bar in bars:
    yval = bar.get_height()
    label_text = f"{yval:.2f}"
    # Use a small, constant offset for label positioning
    label_y_offset = 0.05 
    ax.text(
        bar.get_x() + bar.get_width() / 2.0,
        yval + label_y_offset,
        label_text,
        ha='center', 
        va='bottom', 
        fontsize=7, 
        fontweight='bold'
    )

# --- Formatting for Publication ---
ax.set_title("Forget Accuracy vs Unlearning Step (ECAPA-TDNN)", fontsize=12, fontweight='bold', pad=10)
ax.set_ylabel('Cumulative Avg. FA (%) ↓', fontsize=10, fontweight='bold')
ax.set_xlabel('Continual Unlearning Step', fontsize=10, fontweight='bold')

# Set y-axis limit
ax.set_ylim(0, max(df['cumulative_mean']) * 1.25)
ax.set_xticks(df['step'])
ax.tick_params(axis='x', labelsize=8)
ax.tick_params(axis='y', labelsize=8)

# Remove top and right spines
ax.spines['top'].set_visible(False)
ax.spines['right'].set_visible(False)

fig.tight_layout(pad=0.5)
# plt.show()
plt.savefig("continual_unlearning.png")